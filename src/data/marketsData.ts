// Deterministic interactive chart series generator for any symbol and timeframe
export function generateChartSeries(
  symbol: string,
  basePrice: number,
  isPositive: boolean,
  timeframe: '1D' | '5D' | '1M' | '6M' | 'YTD' | '1Y' | '5Y'
): { time: string; price: number; volume: number }[] {
  const count = 48;
  let seed = 0;
  for (let i = 0; i < symbol.length; i++) {
    seed = (seed * 31 + symbol.charCodeAt(i)) % 10000;
  }
  const tfMultiplier =
    timeframe === '1D'
      ? 0.018
      : timeframe === '5D'
      ? 0.035
      : timeframe === '1M'
      ? 0.065
      : timeframe === '6M'
      ? 0.14
      : timeframe === 'YTD'
      ? 0.18
      : timeframe === '1Y'
      ? 0.24
      : 0.48;

  const points: { time: string; price: number; volume: number }[] = [];
  const startOffset = isPositive ? -basePrice * tfMultiplier * 0.65 : basePrice * tfMultiplier * 0.55;
  let current = basePrice + startOffset;

  for (let i = 0; i < count; i++) {
    seed = (seed * 16807 + 11) % 2147483647;
    const pseudoRand = (seed % 1000) / 1000 - 0.485;
    const progress = i / (count - 1);
    const targetDrift = isPositive ? 0.0022 : -0.0018;
    const step = basePrice * tfMultiplier * 0.08 * (pseudoRand + targetDrift);
    if (i === count - 1) {
      current = basePrice;
    } else {
      current = Math.max(basePrice * 0.25, current + step);
      // Smoothly pull toward final basePrice near the end
      current = current * (1 - progress * 0.15) + basePrice * (progress * 0.15);
    }

    let label = '';
    if (timeframe === '1D') {
      const totalMins = 9 * 60 + 30 + Math.floor((i / (count - 1)) * 390);
      const hrs = Math.floor(totalMins / 60);
      const mins = totalMins % 60;
      label = `${hrs.toString().padStart(2, '0')}:${mins.toString().padStart(2, '0')}`;
    } else {
      label = `Pt ${i + 1}`;
    }

    const vol = Math.floor(1500000 + ((seed % 800) / 800) * 4200000);
    points.push({
      time: label,
      price: Number(current.toFixed(basePrice < 10 ? 4 : 2)),
      volume: vol,
    });
  }

  return points;
}
